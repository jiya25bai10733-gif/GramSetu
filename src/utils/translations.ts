/**
 * Translation helper function
 */
export const getTranslation = (
  key: string,
  lang: 'hi' | 'en' | 'malwi' = 'hi',
  fallback?: string
): string => {
  const item = TRANSLATIONS[key];
  if (item && item[lang]) {
    return item[lang];
  }
  if (item && item.hi) {
    return item.hi;
  }
  return fallback || key;
};
